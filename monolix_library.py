def filter_models(category=None, admin=None, delay=None, absorption=None, distrib=None, elim=None, param=None, search_query=None):
    """Lọc danh mục mô hình Monolix đa chiều theo các tiêu chí chuẩn."""
    results = []
    q = (search_query or "").strip().lower()
    for m in MONOLIX_LIBRARY:
        if category and category != "Tất cả" and m.get("category") != category:
            continue
        if admin and admin != "Tất cả" and m.get("admin") != admin:
            continue
        if delay and delay != "Tất cả" and m.get("delay") != delay:
            continue
        if absorption and absorption != "Tất cả" and m.get("absorption") != absorption:
            continue
        if distrib and distrib != "Tất cả" and m.get("distrib") != distrib:
            continue
        if elim and elim != "Tất cả" and m.get("elim") != elim:
            continue
        if param and param != "Tất cả" and m.get("param") != param:
            continue
        if q:
            match_id = q in m.get("id", "").lower()
            match_desc = q in m.get("desc", "").lower()
            match_params = any(q in p.lower() for p in m.get("params", []))
            if not (match_id or match_desc or match_params):
                continue
        results.append(m)
    return results
